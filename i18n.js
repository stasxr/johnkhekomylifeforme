  var LANG_ORDER = ["en", "ru", "uk", "kk"];

  // Определить стартовый язык: сохранённый → язык браузера → английский
  function detectLang() {
    try {
      var saved = localStorage.getItem("yamoguvse_lang");
      if (saved && I18N[saved]) return saved;
    } catch (e) {}
    var cands = [];
    if (navigator.languages) cands = cands.concat(navigator.languages);
    if (navigator.language) cands.push(navigator.language);
    for (var i = 0; i < cands.length; i++) {
      var code = String(cands[i] || "").toLowerCase().slice(0, 2);
      if (I18N[code]) return code;
    }
    return "en";
  }

  window.I18N = I18N;
  window.I18N_LANGS = LANG_ORDER;
  window.detectLang = detectLang;
